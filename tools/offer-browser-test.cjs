const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true});
 const base = 'http://127.0.0.1:8080/oferta/ci-offer-synthetic-42/';
 const errors = [];
 fs.mkdirSync('artifacts', {recursive:true});
 const context = await browser.newContext({viewport:{width:1440,height:1000}});
 // No external requests (Cookiebot, fonts or any third-party tags).
 await context.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:8080/') ? route.continue() : route.abort());
 const page = await context.newPage();
 page.on('pageerror', e=>errors.push(e.message));
 const response = await page.goto(base);
 assert.equal(response.status(),200);
 assert.match(await page.locator('h1').innerText(),/Oferta testowa/);
 await page.locator('#sec-cennik').scrollIntoViewIfNeeded();
 await page.locator('input[name=commit][value=plus]').check();
 assert.match(await page.locator('#summaryOfferPrice').innerText(),/2 800/);
 await page.locator('#btn-offer-accept-pricing').click();
 await page.locator('#accept_email').fill('test@example.invalid');
 await page.locator('[data-step="1"] button.btn-p').click();
 await page.locator('input[name=accept_timeline][value=asap]').check();
 await page.locator('input[name=accept_ad_budget][value=3_5k]').check();
 await page.locator('[data-step="2"] button.btn-p').click();
 await page.locator('input[name=accept_decision][value=me]').check();
 await page.locator('[data-step="3"] button.btn-p').click();
 assert.equal(await page.locator('.ups-modal-step.active').getAttribute('data-step'),'4');
 await page.screenshot({path:'artifacts/acceptance-desktop.png'});
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#ups-modal-contact').getAttribute('aria-hidden'),'true');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.reload();
 await page.locator('#btn-offer-accept-mobile').waitFor({state:'visible'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'mobile layout overflows');
 await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
 // Real WordPress AJAX, invalid token must fail. No real contacts or mail.
 const offerId = await page.locator('input[name=offer_id]').first().inputValue();
 let result = await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:{action:'upsellio_offer_track_event',offer_id:offerId,offer_token:'invalid',event_name:'offer_view'}});
 assert.equal(result.status(),403);
 // Inject synthetic consent locally; no external CMP required.
 await page.evaluate(()=>{window.Cookiebot={consent:{statistics:true,marketing:false}};window.dispatchEvent(new Event('CookiebotOnConsentReady'));});
 await page.waitForTimeout(1500);
 await page.locator('input[name=commit][value=base]').check();
 await page.locator('#btn-offer-accept-mobile').click();
 await page.locator('#accept_email').fill('test@example.invalid');
 await page.locator('[data-step="1"] button.btn-p').click();
 await page.locator('input[name=accept_timeline][value=asap]').check();
 await page.locator('input[name=accept_ad_budget][value=3_5k]').check();
 await page.locator('[data-step="2"] button.btn-p').click();
 await page.locator('input[name=accept_decision][value=me]').check();
 await page.locator('[data-step="3"] button.btn-p').click();
 const [accept] = await Promise.all([page.waitForResponse(r=>r.url().includes('admin-ajax.php') && (r.request().postData()||'').includes('upsellio_offer_accept_full')),page.locator('#ups-modal-contact-submit').click()]);
 assert.equal((await accept.json()).success,true);
 await page.waitForFunction(()=>document.querySelector('#btn-offer-accept-mobile').disabled);
 await page.screenshot({path:'artifacts/accepted-mobile.png'});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Desktop/mobile and real WordPress acceptance integration passed.');
})().catch(e=>{console.error(e);process.exit(1);});
