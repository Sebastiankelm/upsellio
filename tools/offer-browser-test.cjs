const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true});
 const base = 'http://127.0.0.1:8080/oferta/ci-offer-synthetic-42/';
 const errors = [];
 const telemetry = [];
 const externalRequests = [];
 fs.mkdirSync('artifacts', {recursive:true});
 const context = await browser.newContext({viewport:{width:1440,height:1000}});
 // No external requests (Cookiebot, fonts or any third-party tags).
 await context.route('**/*', route => { const url=route.request().url(); if(url.startsWith('http://127.0.0.1:8080/'))return route.continue(); externalRequests.push(url); return route.abort(); });
 const page = await context.newPage();
 page.on('pageerror', e=>errors.push(e.message));
 page.on('request', req=>{const form=new URLSearchParams(req.postData()||'');if(form.get('action')==='upsellio_offer_track_event')telemetry.push(Object.fromEntries(form));});
 const response = await page.goto(base);
 assert.equal(response.status(),200);
 assert.match(await page.locator('h1').innerText(),/Oferta testowa/);
 await page.locator('#sec-cennik').scrollIntoViewIfNeeded();
 await page.locator('input[name=commit][value=plus]').check();
 assert.match(await page.locator('#summaryOfferPrice').innerText(),/2 800/);
 await page.locator('#btn-offer-accept-pricing').click();
 await page.locator('#accept_email').fill('test@example.invalid');
 await page.locator('[data-step="1"] button.btn-p').click();
 await page.locator('input[name=accept_timeline][value=asap]').check();
 await page.locator('input[name=accept_ad_budget][value=3_5k]').check();
 await page.locator('[data-step="2"] button.btn-p').click();
 await page.locator('input[name=accept_decision][value=me]').check();
 await page.locator('[data-step="3"] button.btn-p').click();
 assert.equal(await page.locator('.ups-modal-step.active').getAttribute('data-step'),'4');
 await page.screenshot({path:'artifacts/acceptance-desktop.png'});
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#ups-modal-contact').getAttribute('aria-hidden'),'true');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.reload();
 await page.locator('#btn-offer-accept-mobile').waitFor({state:'visible'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1),'mobile layout overflows');
 await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
 assert.equal(telemetry.length,0,'No analytics before consent');
 assert(!externalRequests.some(url=>url.includes('googletagmanager.com')||url.includes('google-analytics.com')),'No shared GTM/GA4 on private offer');
 // Real WordPress AJAX, invalid token must fail. No real contacts or mail.
 const offerId = await page.locator('input[name=offer_id]').first().inputValue();
 let result = await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:{action:'upsellio_offer_track_event',offer_id:offerId,offer_token:'invalid',event_name:'offer_view'}});
 assert.equal(result.status(),403);
 // Inject synthetic consent locally; no external CMP required.
 const [trackingResponse] = await Promise.all([page.waitForResponse(r=>r.url().includes('admin-ajax.php') && (r.request().postData()||'').includes('event_name=offer_view')),page.evaluate(()=>{window.Cookiebot={consent:{statistics:true,marketing:false}};window.dispatchEvent(new Event('CookiebotOnConsentReady'));})]);
 assert.equal((await trackingResponse.json()).success,true,'Consent produces accepted event');
 const event=telemetry.find(e=>e.event_name==='offer_view');
 assert(event && event.session_id && event.event_id);
 assert(!event.gclid && !event.client_id && !event.person_id,'Statistics only has no advertising or client identifier');
 const duplicate=await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:event});
 assert.equal((await duplicate.json()).data.duplicate,true,'Repeated event ID deduplicated');
 const invalid=await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:{...event,event_id:'ci-invalid-event-1234',event_name:'offer_accept_step',section_id:'step_9'}});
 assert.equal(invalid.status(),400,'Invalid acceptance step rejected');
 // Real Q&A request, retaining canonical question text rather than arbitrary POST keys.
 const qa=await page.locator('#qaForm').evaluate(form=>Object.fromEntries(new FormData(form)));
 const fingerprint=await page.locator('script').evaluateAll(nodes=>{const script=nodes.find(n=>n.textContent.includes('var offerFingerprint='));const m=script?.textContent.match(/var offerFingerprint=("[^"]+");/);return m?JSON.parse(m[1]):'';});
 assert(fingerprint,'Fixture has commercial fingerprint');
 const qaResponse=await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:{...qa,offer_token:event.offer_token,offer_fingerprint:fingerprint,qa_email:'test@example.invalid',answer_0:'Budżet testowy 4000 zł',answer_999:'Unknown answer must not persist'}});
 assert.equal((await qaResponse.json()).success,true,'Q&A accepted');
 
 await page.locator('input[name=commit][value=base]').check();
 await page.locator('#btn-offer-accept-mobile').click();
 await page.locator('#accept_email').fill('test@example.invalid');
 await page.locator('[data-step="1"] button.btn-p').click();
 await page.locator('input[name=accept_timeline][value=asap]').check();
 await page.locator('input[name=accept_ad_budget][value=3_5k]').check();
 await page.locator('[data-step="2"] button.btn-p').click();
 await page.locator('input[name=accept_decision][value=me]').check();
 await page.locator('[data-step="3"] button.btn-p').click();
 const staleRoute = '**/wp-admin/admin-ajax.php';
 const staleHandler=route=>{const data=new URLSearchParams(route.request().postData()||'');if(data.get('action')!=='upsellio_offer_accept_full')return route.continue();data.set('offer_fingerprint','stale-fingerprint');return route.continue({postData:data.toString()});};
 await page.route(staleRoute,staleHandler);
 const [stale]=await Promise.all([page.waitForResponse(r=>r.url().includes('admin-ajax.php')&&(r.request().postData()||'').includes('upsellio_offer_accept_full')),page.locator('#ups-modal-contact-submit').click()]);
 assert.equal(stale.status(),409,'Stale terms rejected');
 await page.unroute(staleRoute,staleHandler);
 await page.waitForFunction(()=>!document.querySelector('#ups-modal-contact-submit').disabled);
 const [accept] = await Promise.all([page.waitForResponse(r=>r.url().includes('admin-ajax.php') && (r.request().postData()||'').includes('upsellio_offer_accept_full')),page.locator('#ups-modal-contact-submit').click()]);
 assert.equal((await accept.json()).success,true);
 const repeat=await context.request.post('http://127.0.0.1:8080/wp-admin/admin-ajax.php',{form:Object.fromEntries(new URLSearchParams(accept.request().postData()))});
 assert.equal(repeat.status(),409,'Repeated acceptance rejected');
 await page.waitForFunction(()=>document.querySelector('#btn-offer-accept-mobile').disabled);
 await page.screenshot({path:'artifacts/accepted-mobile.png'});
 await page.reload();
 assert(await page.locator('#btn-offer-accept-mobile').isDisabled(),'Accepted status persists across reload');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Desktop/mobile and real WordPress acceptance integration passed.');
})().catch(e=>{console.error(e);process.exit(1);});
